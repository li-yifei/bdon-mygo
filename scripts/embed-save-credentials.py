"""Build the save decryption credentials into the app at build time.

Usage: embed-save-credentials.py OUTPUT.go [--local]

Reads the build credentials from the environment (or, with --local, a local
configuration file) and writes a git-ignored Go file that registers them.
Without credentials it removes OUTPUT and exits 0. Never prints a secret.
"""
import os, re, sys
from pathlib import Path

HEX64 = re.compile(r"^[0-9a-fA-F]{64}$")


def from_env():
    return os.environ.get("OURNOTES_SAVE_KEY", "").strip(), os.environ.get("OURNOTES_SAVE_MAGIC", "").strip()


def from_file():
    for c in (os.environ.get("OURNOTES_SAVE_CREDENTIALS", ""),
              str(Path.home() / ".config/bdon-mygo/save.env"),
              str(Path.home() / ".config/ournotes/save.env")):
        if c and Path(c).is_file():
            values = {}
            for line in Path(c).read_text().splitlines():
                name, sep, value = line.strip().partition("=")
                if sep:
                    values.setdefault(name.strip(), value.strip().strip("\"'"))
            return values.get("OURNOTES_SAVE_KEY", ""), values.get("OURNOTES_SAVE_MAGIC", "")
    return "", ""


def masked(h):
    return "".join(f"{int(h[i*2:i*2+2], 16) ^ ((i * 29 + 71) & 255):02x}" for i in range(32))


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    out = Path(sys.argv[1])
    key, magic = from_env()
    source = "environment"
    if not (key or magic) and "--local" in sys.argv[2:]:
        key, magic = from_file()
        source = "local save.env"
    if not (key or magic):
        out.unlink(missing_ok=True)
        print("save credentials: not built in", file=sys.stderr)
        return
    if not (HEX64.match(key) and HEX64.match(magic)):
        sys.exit("save credentials: OURNOTES_SAVE_KEY and OURNOTES_SAVE_MAGIC must be 64 hex digits")
    out.write_text(f"""// Code generated by scripts/embed-save-credentials.py. DO NOT EDIT. Not committed.

package main

func init() {{
	extensionSaveCredentials = func() (key, magic [32]byte, ok bool) {{
		return maskedSecret("{masked(key)}"), maskedSecret("{masked(magic)}"), true
	}}
}}
""")
    out.chmod(0o600)
    print(f"save credentials: built in from the {source}", file=sys.stderr)


main()
